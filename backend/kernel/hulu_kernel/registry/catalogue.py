"""Generate the block catalogue page from the block manifests (the catalogue is generated, not hand-written)."""

from __future__ import annotations

from pathlib import Path

from hulu_kernel.registry.capabilities import KERNEL_CAPABILITIES
from hulu_kernel.registry.manifest import BlockManifest, load_block_manifest


def _cell(items: list[str]) -> str:
    return "<br>".join(f"`{i}`" for i in items) if items else "none"


def render_catalogue(blocks_root: Path) -> str:
    blocks = [load_block_manifest(p) for p in sorted(blocks_root.glob("*/*/manifest.yaml"))]
    blocks.sort(key=lambda m: (m.family, m.id))
    lines = [
        "# Block catalogue",
        "",
        "<!-- Generated by `uv run hulu-kernel catalogue` from the block manifests. Do not edit by hand. -->",
        "",
        "What every block offers, needs, emits and consumes. To change an entry, edit the block's `manifest.yaml`.",
        "",
        "## Blocks",
        "",
        "| Block | Version | Status | Steward | Summary |",
        "|---|---|---|---|---|",
    ]
    for m in blocks:
        lines.append(f"| `{m.id}` | {m.version} | {m.status} | {m.steward} | {m.summary} |")

    lines += [
        "",
        "## Capabilities: who provides, who needs",
        "",
        "| Capability | Provided by | Required by |",
        "|---|---|---|",
    ]
    caps: dict[str, tuple[list[str], list[str]]] = {}
    for m in blocks:
        for c in m.provides:
            caps.setdefault(c, ([], []))[0].append(m.id)
        for c in m.requires:
            caps.setdefault(c, ([], []))[1].append(m.id)
    for cap in sorted(caps):
        provided, required = caps[cap]
        who = _cell(provided) if provided else ("kernel" if cap in KERNEL_CAPABILITIES else "**nobody yet**")
        lines.append(f"| `{cap}` | {who} | {_cell(required)} |")

    lines += ["", "## Events", "", "| Event | Emitted by | Consumed by |", "|---|---|---|"]
    events: dict[str, tuple[list[str], list[str]]] = {}
    for m in blocks:
        for e in m.events_emitted:
            events.setdefault(e, ([], []))[0].append(m.id)
        for e in m.events_consumed:
            events.setdefault(e, ([], []))[1].append(m.id)
    for ev in sorted(events):
        emitted, consumed = events[ev]
        lines.append(f"| `{ev}` | {_cell(emitted) if emitted else 'kernel or not yet built'} | {_cell(consumed)} |")

    lines += ["", "## Permissions", "", "| Block | Permissions |", "|---|---|"]
    for m in blocks:
        lines.append(f"| `{m.id}` | {_cell(m.permissions)} |")

    lines += ["", "## Dependency graph", "", "```mermaid", "graph LR"]
    provider_of = {c: m.id for m in blocks for c in m.provides}
    edges = sorted({(m.id, provider_of[c]) for m in blocks for c in m.requires if c in provider_of})
    for a, b in edges:
        lines.append(f"  {a.replace('.', '_')}[{a}] --> {b.replace('.', '_')}[{b}]")
    lines += ["```", ""]
    return "\n".join(lines)


def block_ids(blocks_root: Path) -> list[BlockManifest]:
    return [load_block_manifest(p) for p in sorted(blocks_root.glob("*/*/manifest.yaml"))]
